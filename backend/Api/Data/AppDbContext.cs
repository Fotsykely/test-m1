using Api.Entities;
using Microsoft.EntityFrameworkCore;

namespace Api.Data;

public class AppDbContext(DbContextOptions<AppDbContext> options) : DbContext(options)
{
    public DbSet<Item> Items => Set<Item>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<Item>(item =>
        {
            item.Property(i => i.Name).HasMaxLength(Item.NameMaxLength);
            item.Property(i => i.Description).HasMaxLength(Item.DescriptionMaxLength);

            // The status is stored as text ("Draft", "Active", "Archived"): readable directly in SQL.
            item.Property(i => i.Status).HasConversion<string>().HasMaxLength(20);

            // The creation date is generated by MySQL, not by application code.
            item.Property(i => i.CreatedAt).HasDefaultValueSql("CURRENT_TIMESTAMP(6)");
        });
    }
}
